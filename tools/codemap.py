#!/usr/bin/env python3
"""FORGEX CODEMAP (stdlib only): write forgex/CODEMAP.md = key dirs + files + exported symbols, size-capped.

  codemap.py [root] [--max-lines 200] [--out forgex/CODEMAP.md]
Uses `git ls-files` when available (respects .gitignore), else walks the tree. Re-run after big changes.
Lines tagged `# note:` under "## Notes" in an existing CODEMAP are kept.
"""
import argparse, re, subprocess
from collections import defaultdict
from pathlib import Path

SKIP = re.compile(r"(^|/)(node_modules|\.next|dist|build|coverage|\.git|public|assets|vendor|forgex/tasks)(/|$)|\.(lock|png|jpe?g|gif|svg|ico|webp|ttf|woff2?|map|sql)$|lock\.(json|yaml)$")
CODE = {".ts", ".tsx", ".js", ".jsx", ".mjs", ".py", ".go", ".rs"}
EXP = re.compile(r"^export\s+(?:default\s+)?(?:async\s+)?(?:function\*?|const|let|class|type|interface|enum)\s+([A-Za-z_$][\w$]*)", re.M)
PYDEF = re.compile(r"^(?:def|class)\s+([A-Za-z]\w*)", re.M)

def files(root):
    try:
        out = subprocess.run(["git", "ls-files"], cwd=root, capture_output=True, text=True, check=True).stdout.split()
    except Exception:
        out = [str(p.relative_to(root)) for p in root.rglob("*") if p.is_file()]
    return sorted(f for f in out if not SKIP.search(f))

def symbols(path):
    try: text = path.read_text(errors="ignore")[:60000]
    except Exception: return []
    names = (PYDEF if path.suffix == ".py" else EXP).findall(text)
    return [n for n in names if not n.startswith("_")][:6]

def main():
    ap = argparse.ArgumentParser(); ap.add_argument("root", nargs="?", default=".")
    ap.add_argument("--max-lines", type=int, default=200); ap.add_argument("--out", default="forgex/CODEMAP.md")
    a = ap.parse_args(); root = Path(a.root).resolve(); out = root / a.out
    notes = []
    if out.exists():
        t = out.read_text(); notes = t.split("## Notes", 1)[1].strip().splitlines() if "## Notes" in t else []
    by_dir = defaultdict(list)
    for f in files(root): by_dir[str(Path(f).parent)].append(f)
    lines = ["# CODEMAP (generated by codemap.py; read this before opening files)", ""]
    for d in sorted(by_dir):
        fs = by_dir[d]
        lines.append(f"## {d}/ ({len(fs)} files)")
        for f in fs[:25]:
            p = root / f
            syms = symbols(p) if p.suffix in CODE else []
            lines.append(f"- `{Path(f).name}`" + (f": {', '.join(syms)}" if syms else ""))
        if len(fs) > 25: lines.append(f"- … {len(fs) - 25} more")
    body = lines[: a.max_lines]
    if len(lines) > a.max_lines: body.append(f"_truncated at {a.max_lines} lines; run with --max-lines N or a subdir root_")
    body += ["", "## Notes", *(notes or ["# note: add one-line hints here; they survive refresh"])]
    out.parent.mkdir(parents=True, exist_ok=True); out.write_text("\n".join(body) + "\n")
    print(f"wrote {out.relative_to(root)} ({len(body)} lines)")

if __name__ == "__main__":
    main()
